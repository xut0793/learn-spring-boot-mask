package com.learn.mask.tutorial.ch06;

/**
 * 一次脱敏调用的结果分类。
 * <p>
 * 它同时是三个东西：
 * <ul>
 *   <li>引擎判定链的**出口标记**——每条分支都以一个 action 结束</li>
 *   <li>Micrometer 的**指标标签**（第 8 章）</li>
 *   <li>测试的**断言对象**——可以断言「走的是哪条分支」，而不只是「结果对不对」</li>
 * </ul>
 * 第三点很重要：`138****5678` 这个结果可能来自「实际脱敏」也可能来自「缓存命中」，
 * 只看返回值区分不出来。
 */
public enum MaskAction {

    /** 实际执行了脱敏（含缓存命中，因为对调用方而言语义相同）。 */
    MASK,

    /** 旁路：总开关关闭、值为空、角色在旁路列表、规则被禁用。 */
    BYPASS,

    /** 幂等跳过：值已经是当前规则的打码形态。 */
    SKIP_ALREADY_MASKED,

    /** 策略抛异常。注意引擎会重新抛出，不吞掉。 */
    FAIL
}
